import pino, { type Logger } from 'pino';
import type { AppConfig } from '@ticketflow/config';

/**
 * Structured logging (Pino, JSON lines).
 *
 * Guarantees enforced here rather than by convention:
 * - `redact` drops credential-ish fields even if a future handler logs a whole request object;
 * - messages never contain client bodies; handlers log identifiers and outcomes only;
 * - in `test` logging is disabled unless `TF_TEST_LOGS=1`, so Vitest output stays readable.
 */

const REDACT_PATHS = [
  'password',
  'req.headers.authorization',
  'req.headers.cookie',
  'res.headers["set-cookie"]',
  'AUTH_SECRET',
  'DATABASE_URL',
  'REDIS_URL',
  '*.email',
];

export function createLogger(config: AppConfig): Logger {
  const silent = config.NODE_ENV === 'test' && process.env.TF_TEST_LOGS !== '1';

  return pino({
    name: 'ticketflow-api',
    level: config.LOG_LEVEL,
    base: { environment: config.NODE_ENV },
    redact: { paths: REDACT_PATHS, censor: '[redacted]' },
    // Timestamps in epoch millis are cheaper to sort in log pipelines than ISO strings.
    timestamp: pino.stdTimeFunctions.isoTime,
    formatters: { level: (label) => ({ level: label }) },
    ...(silent ? { enabled: false } : {}),
  });
}

/** Adds stable correlation fields; `requestId` is generated by middleware, `runId` only in the lab. */
export function childLogger(
  logger: Logger,
  bindings: { requestId?: string; runId?: string; reservationId?: string; strategy?: string },
): Logger {
  const defined = Object.fromEntries(
    Object.entries(bindings).filter(([, value]) => value !== undefined),
  );
  return logger.child(defined);
}

export type { Logger };
